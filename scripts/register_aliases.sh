#!/bin/sh
# Install or refresh permanent iSH aliases, then record their definitions.
# Run with: sh scripts/register_aliases.sh
set -eu

ROOT="$(CDPATH= cd "$(dirname "$0")/.." && pwd -P)" || exit 1
ALIASES="$ROOT/scripts/aliases"
PROFILE="${ISH_PROFILE_FILE:-${HOME:?HOME is not set}/.profile}"
OUTPUT="$ROOT/current_aliases.txt"

for name in sync-apps.sh sync-app.sh git-apply-push.sh tag-apps.sh; do
    if [ ! -f "$ALIASES/$name" ]; then
        echo "Missing alias script: $ALIASES/$name" >&2
        exit 1
    fi
done

if [ -e "$PROFILE" ] && [ ! -f "$PROFILE" ]; then
    echo "Not a regular shell profile: $PROFILE" >&2
    exit 1
fi

# Work on a temporary copy, preserving unrelated profile content.
TMP="$(mktemp "${PROFILE}.tmp.XXXXXX")" || exit 1
trap 'rm -f "$TMP"' 0
trap 'exit 1' 1 2 3 15

if [ -f "$PROFILE" ]; then
    # Remove previous definitions of these aliases, including the old
    # $HOME/sync-apps.sh and $HOME/git-apply-push.sh versions. Also remove
    # an earlier managed block if this installer has run before.
    awk '
        /^# BEGIN iSH-Scripts aliases$/ { managed=1; next }
        /^# END iSH-Scripts aliases$/ { managed=0; next }
        managed { next }
        /^[[:space:]]*alias[[:space:]]+(syncapps|syncapp|gamp|tagapps)=/ { next }
        { line[++n]=$0 }
        END {
            while (n > 0 && line[n] ~ /^[[:space:]]*$/) n--
            for (i=1; i<=n; i++) print line[i]
        }
    ' "$PROFILE" > "$TMP"
fi

{
    printf '\n# BEGIN iSH-Scripts aliases\n'
    printf 'alias syncapps=\047sh "%s/sync-apps.sh"\047\n' "$ALIASES"
    printf 'alias syncapp=\047sh "%s/sync-app.sh"\047\n' "$ALIASES"
    printf 'alias gamp=\047sh "%s/git-apply-push.sh"\047\n' "$ALIASES"
    printf 'alias tagapps=\047sh "%s/tag-apps.sh"\047\n' "$ALIASES"
    printf '# END iSH-Scripts aliases\n'
} >> "$TMP"

mv -f "$TMP" "$PROFILE"
trap - 0

# A standalone script cannot modify the aliases of its parent shell. This
# records ALL persistent aliases declared in the updated profile instead.
{
    printf '# Persistent aliases from %s\n' "$PROFILE"
    printf '# Generated by scripts/register_aliases.sh; not tracked by Git.\n'
    awk '/^[[:space:]]*alias[[:space:]]+/ { print }' "$PROFILE"
} > "$OUTPUT"

printf 'Registered syncapps, syncapp, gamp, and tagapps in %s\n' "$PROFILE"
printf 'Alias snapshot: %s\n' "$OUTPUT"
printf 'To activate in this terminal: . "%s"\n' "$PROFILE"
